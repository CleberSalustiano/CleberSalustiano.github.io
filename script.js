const defaultLanguage = "pt";
const header = document.querySelector("[data-header]");
const nav = document.querySelector("[data-nav]");
const navToggle = document.querySelector("[data-nav-toggle]");
const year = document.querySelector("[data-year]");
const revealItems = document.querySelectorAll("[data-reveal]");
const techTrack = document.querySelector("[data-tech-track]");
const languageButtons = document.querySelectorAll("[data-lang-option]");
let currentLanguage = defaultLanguage;

document.documentElement.classList.add("js");

if (year) {
  year.textContent = new Date().getFullYear();
}

const getTranslation = (language, key) => {
  const read = (bundle) =>
    key.split(".").reduce((value, segment) => {
      if (value && typeof value === "object" && segment in value) {
        return value[segment];
      }

      return undefined;
    }, bundle);

  return read(translations[language]) ?? read(translations[defaultLanguage]) ?? "";
};

const attributeNameFromDatasetKey = (key) => {
  const raw = key.slice(4);
  if (!raw) {
    return "";
  }

  return (raw.charAt(0).toLowerCase() + raw.slice(1)).replace(/[A-Z]/g, (character) => `-${character.toLowerCase()}`);
};

const populateTechTrack = (labels) => {
  if (!techTrack) {
    return;
  }

  techTrack.innerHTML = "";
  [...labels, ...labels].forEach((label) => {
    const item = document.createElement("span");
    item.textContent = label;
    techTrack.appendChild(item);
  });
};

const updateLanguageButtons = () => {
  languageButtons.forEach((button) => {
    const isActive = button.dataset.langOption === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });
};

const updateNavToggleLabel = () => {
  if (!navToggle) {
    return;
  }

  const key = nav?.classList.contains("is-open") ? "aria.navToggleClose" : "aria.navToggleOpen";
  navToggle.setAttribute("aria-label", getTranslation(currentLanguage, key));
};

const applyTranslations = (language) => {
  currentLanguage = translations[language] ? language : defaultLanguage;
  document.documentElement.lang = translations[currentLanguage].langCode;

  document
    .querySelectorAll("[data-i18n], [data-i18n-content], [data-i18n-alt], [data-i18n-aria-label], [data-i18n-placeholder]")
    .forEach((element) => {
      if (element.dataset.i18n) {
        element.textContent = getTranslation(currentLanguage, element.dataset.i18n);
      }

      Object.entries(element.dataset).forEach(([key, translationKey]) => {
        if (!key.startsWith("i18n") || key === "i18n") {
          return;
        }

        const attributeName = attributeNameFromDatasetKey(key);
        if (!attributeName) {
          return;
        }

        const translatedValue = getTranslation(currentLanguage, translationKey);
        if (typeof translatedValue === "string") {
          element.setAttribute(attributeName, translatedValue);
        }
      });
    });

  populateTechTrack(translations[currentLanguage].tech);
  updateLanguageButtons();
  updateNavToggleLabel();
};

const saveLanguagePreference = (language) => {
  try {
    window.localStorage.setItem("portfolio-language", language);
  } catch {
    // Ignore storage failures.
  }
};

const loadLanguagePreference = () => {
  try {
    return window.localStorage.getItem("portfolio-language");
  } catch {
    return null;
  }
};

const setHeaderState = () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 12);
};

setHeaderState();
window.addEventListener("scroll", setHeaderState, { passive: true });

navToggle?.addEventListener("click", () => {
  const isOpen = nav?.classList.toggle("is-open") ?? false;
  document.body.classList.toggle("nav-open", isOpen);
  navToggle.setAttribute("aria-expanded", String(isOpen));
  updateNavToggleLabel();
});

nav?.addEventListener("click", (event) => {
  if (!(event.target instanceof HTMLAnchorElement)) {
    return;
  }

  nav.classList.remove("is-open");
  document.body.classList.remove("nav-open");
  navToggle?.setAttribute("aria-expanded", "false");
  updateNavToggleLabel();
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const selectedLanguage = button.dataset.langOption;
    if (!selectedLanguage || selectedLanguage === currentLanguage) {
      return;
    }

    applyTranslations(selectedLanguage);
    saveLanguagePreference(selectedLanguage);
  });
});

const preferredLanguage = loadLanguagePreference() ?? defaultLanguage;
applyTranslations(preferredLanguage);

const revealItemsInInitialViewport = () => {
  if (window.innerWidth <= 760) {
    return;
  }

  const revealThreshold = window.innerHeight * 1.04;

  revealItems.forEach((item) => {
    const { top } = item.getBoundingClientRect();
    if (top <= revealThreshold) {
      item.classList.add("is-visible");
    }
  });
};

revealItemsInInitialViewport();

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) {
          return;
        }

        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      });
    },
    {
      rootMargin: "0px 0px -12% 0px",
      threshold: 0.18,
    },
  );

  revealItems.forEach((item) => revealObserver.observe(item));
} else {
  revealItems.forEach((item) => item.classList.add("is-visible"));
}
